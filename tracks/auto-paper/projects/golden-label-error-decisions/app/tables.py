"""LaTeX table bodies for the paper, generated from ../results so no number is typed by hand.

Writes tabular environments to ../outputs/week-04/tables/; captions and float placement live in paper.tex.
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
T = ROOT / "outputs/week-04/tables"
T.mkdir(parents=True, exist_ok=True)
MINUS = "−"


def num(x, d=2):
    s = f"{x:,.{d}f}"
    return s.replace("-", MINUS)


def write(name, lines):
    (T / f"{name}.tex").write_text("% generated by app/tables.py from results/; do not edit by hand\n"
                                   + "\n".join(lines) + "\n")


# Natural experiment (delta = 3 pp).
f = pd.read_csv(R / "e1_flips.csv")
x = json.load(open(R / "e1_extra.json"))
full = f[(f.level == "full") & (f.delta == 0.03)].set_index("scope")
sub = f[(f.level == "subject") & (f.delta == 0.03)][["pairs", "flips", "lost", "spurious", "reversals", "ref_decided"]].sum()
mh = next(r for r in x["full_mcnemar_holm"] if r["delta"] == 0.03)
smh = x["subject_mcnemar_holm_delta3"]
row = lambda name, dec, fl, lo, sp, rv: f"{name} & {dec} & {fl} & {lo} & {sp} & {rv} \\\\"
c = lambda v: f"{int(v):,}"
write("tab_natural", [
    r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
    r"조건 & 기준 우세 & 반전 & 상실 & 허위 & 역전 \\", r"\midrule",
    rf"\multicolumn{{6}}{{@{{}}l}}{{\textit{{전체 셋, {c(full.loc['orig_S', 'pairs'])}쌍}}}} \\",
    row(r"$S$의 원래 정답", *(c(full.loc["orig_S", k]) for k in ["ref_decided", "flips", "lost", "spurious", "reversals"])),
    row(r"공개 점수", *(c(full.loc["published_all", k]) for k in ["ref_decided", "flips", "lost", "spurious", "reversals"])),
    row(r"McNemar--Holm", *(c(mh[k]) for k in ["decided", "flips", "lost", "spurious", "reversals"])),
    r"\midrule",
    rf"\multicolumn{{6}}{{@{{}}l}}{{\textit{{과목 단위 셋, {x['subject_flip_correlation']['n_subjects']}과목, {c(sub.pairs)}쌍}}}} \\",
    row(r"$S$의 원래 정답", *(c(sub[k]) for k in ["ref_decided", "flips", "lost", "spurious", "reversals"])),
    row(r"McNemar--Holm", "--", c(smh["flips"]), "--", "--", c(smh["reversals"])),
    r"\bottomrule", r"\end{tabular}"])

# Injection at e = 3 % (delta = 3 pp).
e = pd.read_csv(R / "e2_injection.csv")
mechs = ["random", "uniform_modal", "hard_random", "systematic", "swap", "drop"]
d3 = e[(e.delta == 0.03) & (e.rate == 0.03)].set_index(["n", "mech"])
d0 = e[(e.delta == 0.0) & (e.rate == 0.03)].set_index(["n", "mech"])
cell = lambda tab, n, m, col, scale=100: num(scale * tab.loc[(n, m), col]) if (n, m) in tab.index else "--"
lines = [r"\begin{tabular}{@{}lcccccc@{}}", r"\toprule",
         r" & \multicolumn{4}{c}{라벨 오류} & \multicolumn{2}{c}{기준선(라벨 오류 없음)} \\",
         r"\cmidrule(lr){2-5}\cmidrule(l){6-7}",
         r" & 무작위 & 대표 오답 & 어려운 문항 & 체계적 & 문항 교체 & 문항 제거 \\", r"\midrule",
         r"\multicolumn{7}{@{}l}{\textit{결정 반전율(\%)}} \\"]
for n in sorted(e.n.unique()):
    lines.append(rf"$n$ = {n:,} & " + " & ".join(cell(d3, n, m, "flip_rate") for m in mechs) + r" \\")
lines += [r"\midrule", r"\multicolumn{7}{@{}l}{\textit{$n$ = 870에서 반전의 방향(\%)}} \\"]
lines.append("결정 상실 & " + " & ".join(cell(d3, 870, m, "lost_rate") for m in mechs) + r" \\")
lines.append("허위 결정 & " + " & ".join(cell(d3, 870, m, "spurious_rate") for m in mechs) + r" \\")
lines += [r"\midrule",
          "격차 압축 상관 & " + " & ".join(cell(d0, 870, m, "compress", 1) for m in mechs) + r" \\",
          r"\bottomrule", r"\end{tabular}"]
write("tab_injection", lines)

# Audit operating characteristic (509 items) next to flip rates at the same error rate.
oc = pd.read_csv(R / "e3_audit_oc.csv")
oc = oc[oc.audit_n == 509].set_index("rate")
lines = [r"\begin{tabular}{@{}cccccc@{}}", r"\toprule",
         r" & & \multicolumn{2}{c}{$n$ = 100} & \multicolumn{2}{c}{$n$ = 870} \\",
         r"\cmidrule(lr){3-4}\cmidrule(l){5-6}",
         r"오류율 & 통과 확률 & 무작위 & 체계적 & 무작위 & 체계적 \\", r"\midrule"]
for rate in [0.0025, 0.005, 0.0075, 0.01]:
    vals = [cell(d3_r, n, m, "flip_rate") for d3_r in [e[(e.delta == 0.03) & (e.rate == rate)].set_index(["n", "mech"])]
            for n in [100, 870] for m in ["random", "systematic"]]
    p = 100 * oc.loc[rate, "p_pass_zero_error"]
    lines.append(f"{num(100 * rate)} & {num(p, 1)} & " + " & ".join(vals) + r" \\")
lines += [r"\bottomrule", r"\end{tabular}"]
write("tab_audit", lines)

# Appendix: per-model accuracy (percent) under the three label conditions.
a = pd.read_csv(R / "e1_model_accuracy.csv")
lines = [r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
         r"모델 & 공개 점수 & $S$ 원래 정답 & $S$ 수정 정답 & 변화(\%p) \\", r"\midrule"]
for _, r in a.iterrows():
    name = r.model.replace("_", r"\_")
    lines.append(rf"\texttt{{{name}}} & {num(100 * r.acc_published, 1)} & {num(100 * r.acc_orig_S, 1)} & "
                 rf"{num(100 * r.acc_clean_S, 1)} & {num(r.shift_pp)} \\")
lines += [r"\bottomrule", r"\end{tabular}"]
write("tab_models", lines)
