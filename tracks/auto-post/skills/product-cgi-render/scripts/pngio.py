class Canvas:
    """RGB(3) 또는 RGBA(4) 바이트 캔버스. (0, 0) = 왼쪽 위."""

    def __init__(self, width, height, color=(255, 255, 255), channels=3):
        self.w, self.h, self.ch = int(width), int(height), channels
        px = bytes(color[:channels]) if len(color) >= channels else bytes(color) + b"\xff"
        self.buf = bytearray(px * (self.w * self.h))

    def fill_rect(self, x, y, w, h, color):
        x0, y0 = max(0, int(x)), max(0, int(y))
        x1, y1 = min(self.w, int(x + w)), min(self.h, int(y + h))
        if x1 <= x0 or y1 <= y0:
            return
        px = bytes(color[:self.ch]) if len(color) >= self.ch else bytes(color) + b"\xff"
        row = px * (x1 - x0)
        for yy in range(y0, y1):
            i = (yy * self.w + x0) * self.ch
            self.buf[i:i + len(row)] = row

    def text(self, x, y, s, scale=4, color=(0, 0, 0), spacing=1):
        """5×7 글꼴로 한 줄을 그린다. 그릴 수 없는 글자(한글 등)는 '?'. 그린 폭(px)을 돌려준다."""
        cx = x
        for c in s.upper():
            g = FONT.get(c, FONT["?"])
            for r, bits in enumerate(g):
                for b in range(5):
                    if bits & (1 << (4 - b)):
                        self.fill_rect(cx + b * scale, y + r * scale, scale, scale, color)
            cx += (5 + spacing) * scale
        return cx - x

    @staticmethod
    def text_width(s, scale=4, spacing=1):
        return len(s) * (5 + spacing) * scale

    def save(self, path):
        write_png(path, self.w, self.h, bytes(self.buf), self.ch)


def write_png(path, width, height, data, channels=3):
    """data = 행 우선 RGB/RGBA 바이트. 필터 없음(0)으로 저장한다."""
    color_type = {3: 2, 4: 6}[channels]
    stride = width * channels
    raw = bytearray()
    for y in range(height):
        raw.append(0)
        raw += data[y * stride:(y + 1) * stride]

    def chunk(tag, body):
        c = struct.pack(">I", len(body)) + tag + body
        return c + struct.pack(">I", zlib.crc32(tag + body) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", width, height, 8, color_type, 0, 0, 0)
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(bytes(raw), 6)) + chunk(b"IEND", b""))
